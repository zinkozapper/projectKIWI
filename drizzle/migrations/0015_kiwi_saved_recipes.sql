-- Recipes page: recipes a user saved from Claude's suggestions, with their ingredients.
-- food_groups reuses the AI food workflow's groups (src/lib/food-import/rules.ts FOOD_GROUPS).
-- Ingredients link to the catalog when Claude matched one (food_id), so they can be added to the list.
CREATE TABLE IF NOT EXISTS public.saved_recipe (
  recipe_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
  summary text NOT NULL DEFAULT '' CHECK (char_length(summary) <= 400),
  servings integer NOT NULL DEFAULT 2 CHECK (servings BETWEEN 1 AND 12),
  minutes integer CHECK (minutes BETWEEN 1 AND 600),
  steps text[] NOT NULL DEFAULT '{}' CHECK (cardinality(steps) <= 20),
  food_groups text[] NOT NULL DEFAULT '{}' CHECK (food_groups <@ ARRAY['meat','seafood','grain','legume','bread','fruit','vegetable','dairy','nut_seed','condiment','other']::text[]),
  source text NOT NULL DEFAULT 'claude' CHECK (source IN ('claude', 'user')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS saved_recipe_user_idx ON public.saved_recipe (user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.saved_recipe_ingredient (
  ingredient_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipe_id integer NOT NULL REFERENCES public.saved_recipe(recipe_id) ON DELETE CASCADE,
  position integer NOT NULL DEFAULT 0,
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 120),
  amount text NOT NULL DEFAULT '' CHECK (char_length(amount) <= 60),
  food_id integer REFERENCES public.food(food_id) ON DELETE SET NULL,
  servings double precision NOT NULL DEFAULT 1 CHECK (servings > 0 AND servings <= 50)
);
CREATE INDEX IF NOT EXISTS saved_recipe_ingredient_recipe_idx ON public.saved_recipe_ingredient (recipe_id, position);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.saved_recipe, public.saved_recipe_ingredient TO authenticated;
GRANT ALL ON public.saved_recipe, public.saved_recipe_ingredient TO service_role;

ALTER TABLE public.saved_recipe ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.saved_recipe_ingredient ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users manage own recipes" ON public.saved_recipe;
CREATE POLICY "Users manage own recipes" ON public.saved_recipe FOR ALL TO authenticated
  USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());

DROP POLICY IF EXISTS "Users manage own recipe ingredients" ON public.saved_recipe_ingredient;
CREATE POLICY "Users manage own recipe ingredients" ON public.saved_recipe_ingredient FOR ALL TO authenticated
  USING (EXISTS (SELECT 1 FROM public.saved_recipe r WHERE r.recipe_id = saved_recipe_ingredient.recipe_id AND r.user_id = auth.uid()))
  WITH CHECK (EXISTS (SELECT 1 FROM public.saved_recipe r WHERE r.recipe_id = saved_recipe_ingredient.recipe_id AND r.user_id = auth.uid()));
