CREATE TABLE public.food_category (
  food_category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_description varchar NOT NULL,
  category_serving_modifier double precision NOT NULL DEFAULT 1
);
CREATE TABLE public.food (
  food_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  food_picture varchar,
  food_name varchar NOT NULL,
  food_description text NOT NULL DEFAULT '',
  serving_size double precision NOT NULL DEFAULT 1,
  food_category_id integer REFERENCES public.food_category(food_category_id),
  unit varchar NOT NULL DEFAULT 'pack',
  price numeric NOT NULL DEFAULT 0,
  emoji varchar NOT NULL DEFAULT '',
  nutrition jsonb NOT NULL DEFAULT '{}'::jsonb,
  pairs integer[] NOT NULL DEFAULT '{}'
);
CREATE TABLE public.users (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  first_name varchar NOT NULL DEFAULT '',
  last_name varchar NOT NULL DEFAULT '',
  user_picture varchar,
  email varchar NOT NULL DEFAULT ''
);
CREATE TABLE public.pantry (
  pantry_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL UNIQUE REFERENCES public.users(user_id) ON DELETE CASCADE
);
CREATE TABLE public.pantry_item (
  pantry_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pantry_id integer NOT NULL REFERENCES public.pantry(pantry_id) ON DELETE CASCADE,
  food_id integer NOT NULL REFERENCES public.food(food_id),
  quantity double precision NOT NULL DEFAULT 1 CHECK (quantity > 0),
  unit varchar,
  expiration_date date
);
CREATE TABLE public.shopping_list (
  shopping_list_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  days integer NOT NULL DEFAULT 7,
  budget numeric NOT NULL DEFAULT 75,
  status varchar NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);
CREATE TABLE public.shopping_list_item (
  shopping_list_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shopping_list_id integer NOT NULL REFERENCES public.shopping_list(shopping_list_id) ON DELETE CASCADE,
  food_id integer NOT NULL REFERENCES public.food(food_id),
  quantity double precision NOT NULL DEFAULT 1 CHECK (quantity > 0),
  unit varchar,
  is_purchased boolean NOT NULL DEFAULT false
);

