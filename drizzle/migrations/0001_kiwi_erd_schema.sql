CREATE OR REPLACE FUNCTION public.handle_new_kiwi_user()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  INSERT INTO public.users (user_id, email, first_name, last_name, user_picture)
  VALUES (NEW.id, COALESCE(NEW.email,''),
    COALESCE(NEW.raw_user_meta_data->>'first_name', split_part(COALESCE(NEW.raw_user_meta_data->>'full_name',''),' ',1), ''),
    COALESCE(NEW.raw_user_meta_data->>'last_name', ''),
    NEW.raw_user_meta_data->>'avatar_url')
  ON CONFLICT (user_id) DO NOTHING;
  INSERT INTO public.pantry (user_id) VALUES (NEW.id) ON CONFLICT (user_id) DO NOTHING;
  RETURN NEW;
END $$;
REVOKE EXECUTE ON FUNCTION public.handle_new_kiwi_user() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER on_auth_user_created_kiwi AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION public.handle_new_kiwi_user();

INSERT INTO public.users (user_id, email) SELECT id, COALESCE(email,'') FROM auth.users ON CONFLICT DO NOTHING;
