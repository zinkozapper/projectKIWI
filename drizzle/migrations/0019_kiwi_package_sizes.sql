-- Package sizes: a food (or one of its purchase options from 0018) is bought as a package, not as servings.
-- Each food/option has up to 3 sizes (1 lb, 3 lb family pack …), picked by the AI step of the add-food
-- workflow from the Kroger products it already searched (scripts/kroger/package-sizes-backfill.mjs for the
-- existing catalog). One add on the plan = one package at its real price; its servings are spread across the trip.
--
--   food_package                   One size. servings = package_price / price per serving, so nutrition and
--                                  price stay on the same serving basis as food_price. sort_order 0 = the size
--                                  most shoppers pick; 0–2 + the unique index caps it at 3 per food/option.
--   shopping_list_item.food_package_id   The size picked. Set: quantity = packages. NULL: quantity = servings (older items).
--   shopping_list_item.price_estimate    The shopper's own price when Kiwi has none (per package, or per serving
--                                        when there is no package). Used only while no store price exists.
--   pantry_item.food_package_id          Same as the list: quantity = packages at home. NULL: one package of the
--                                        food's default size (or a week of servings when it has no sizes).
-- Seeds one size per priced food from food_price at the default store (84601). Safe to run more than once.

CREATE TABLE IF NOT EXISTS public.food_package (
  food_package_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  food_id integer NOT NULL REFERENCES public.food(food_id) ON DELETE CASCADE,
  food_option_id bigint,
  label text NOT NULL CHECK (char_length(label) BETWEEN 1 AND 40),
  servings numeric(10,2) NOT NULL CHECK (servings > 0),
  package_grams numeric CHECK (package_grams > 0),
  package_price numeric(10,2) NOT NULL DEFAULT 0 CHECK (package_price >= 0),
  product_id text,
  description text,
  package_size text,
  sort_order smallint NOT NULL DEFAULT 0 CHECK (sort_order BETWEEN 0 AND 2),
  source text NOT NULL DEFAULT 'kroger' CHECK (source IN ('kroger', 'ai')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS food_package_slot_key ON public.food_package (food_id, coalesce(food_option_id, 0), sort_order);
CREATE INDEX IF NOT EXISTS food_package_food_idx ON public.food_package (food_id);
COMMENT ON TABLE public.food_package IS 'Package sizes a food or purchase option is sold in (max 3), each with its price and servings';
COMMENT ON COLUMN public.food_package.servings IS 'Servings in one package, on the food''s nutrition serving (package_price / price per serving)';

-- Link to purchase options once migration 0018 exists (re-running this file after 0018 adds it).
DO $$
BEGIN
  IF to_regclass('public.food_option') IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'food_package_food_option_id_fkey'
  ) THEN
    ALTER TABLE public.food_package ADD CONSTRAINT food_package_food_option_id_fkey
      FOREIGN KEY (food_option_id) REFERENCES public.food_option(food_option_id) ON DELETE CASCADE;
  END IF;
END $$;

ALTER TABLE public.shopping_list_item
  ADD COLUMN IF NOT EXISTS food_package_id bigint REFERENCES public.food_package(food_package_id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS price_estimate numeric(10,2) CHECK (price_estimate > 0);
COMMENT ON COLUMN public.shopping_list_item.food_package_id IS 'Package size picked; set = quantity is packages, NULL = quantity is servings';
COMMENT ON COLUMN public.shopping_list_item.price_estimate IS 'Shopper''s own price when no store price exists (per package, or per serving without a package)';

ALTER TABLE public.pantry_item
  ADD COLUMN IF NOT EXISTS food_package_id bigint REFERENCES public.food_package(food_package_id) ON DELETE SET NULL;
COMMENT ON COLUMN public.pantry_item.food_package_id IS 'Package size at home; quantity = packages';

-- Everyone can read sizes; only the service role writes them.
ALTER TABLE public.food_package ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS food_package_read ON public.food_package;
CREATE POLICY food_package_read ON public.food_package FOR SELECT TO anon, authenticated USING (true);
REVOKE INSERT, UPDATE, DELETE ON public.food_package FROM anon, authenticated;
GRANT SELECT ON public.food_package TO anon, authenticated;
GRANT ALL ON public.food_package TO service_role;

-- Seed: the product each food is already priced on becomes its first size (weight-priced items = 1 lb).
INSERT INTO public.food_package (food_id, label, servings, package_grams, package_price, product_id, description, package_size, sort_order, source)
SELECT fp.food_id,
       left(CASE WHEN lower(coalesce(fp.sold_by, '')) = 'weight' THEN '1 lb' ELSE coalesce(nullif(fp.package_size, ''), 'Package') END, 40),
       round(fp.package_price / fp.price_per_serving, 2),
       fp.package_grams, fp.package_price, fp.product_id, fp.description, fp.package_size, 0, 'kroger'
FROM public.food_price fp
JOIN public.zip_store zs ON zs.location_id = fp.location_id AND zs.zip_code = '84601'
WHERE fp.price_per_serving > 0 AND fp.package_price > 0 AND fp.package_price / fp.price_per_serving >= 0.5
ON CONFLICT DO NOTHING;
