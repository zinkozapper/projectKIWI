-- OKR 2 (Objective 1, effective shopping recommendations): nutrient goal achievement % and history.
--
-- Definitions (the app computes these in src/lib/nutrient-goals.ts, the same math as the plan page):
--   daily target   = targets(profile) in src/lib/foods.ts (calories, protein, carbs, fat, fiber, iron,
--                    calcium, vitamin C, vitamin D), from the user's age, height, weight, sex, activity.
--   pantry supply  = what the pantry holds per day: sum(food nutrition x quantity) / plan days, where
--                    plan days = the budget period length (1, 2 or 4 weeks), like the plan page bars.
--   nutrient met   = pantry supply per day >= 100% of the daily target.
--   achievement %  = nutrients met / nutrients with a target x 100 (one number per snapshot).
--   goal met       = every nutrient met. This is the "pantry meets the goal criteria" moment.
--
-- 1. public.nutrient_profile_snapshot: one row each time a user's pantry (or their targets) changes.
--    That gives the history: when a pantry first met its goals, and whether it stayed there.
--    recommended_food_ids is filled from recommendation_event (0003): the pantry foods this user added
--    from a recommendation, so OKR 2 can be split by "followed recommendations" vs not.
CREATE TABLE public.nutrient_profile_snapshot (
  nutrient_profile_snapshot_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES public.users(user_id) ON DELETE CASCADE,
  pantry_id integer NOT NULL REFERENCES public.pantry(pantry_id) ON DELETE CASCADE,
  plan_days smallint NOT NULL CHECK (plan_days > 0),
  nutrients jsonb NOT NULL,
  nutrients_met smallint NOT NULL CHECK (nutrients_met >= 0),
  nutrients_total smallint NOT NULL CHECK (nutrients_total >= 0 AND nutrients_met <= nutrients_total),
  achievement_pct numeric(5,1) NOT NULL CHECK (achievement_pct BETWEEN 0 AND 100),
  avg_coverage_pct numeric(5,1) NOT NULL CHECK (avg_coverage_pct BETWEEN 0 AND 100),
  goal_met boolean NOT NULL,
  pantry_food_ids integer[] NOT NULL DEFAULT '{}',
  recommended_food_ids integer[] NOT NULL DEFAULT '{}',
  pantry_signature text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX nutrient_profile_snapshot_user_time_idx ON public.nutrient_profile_snapshot (user_id, created_at DESC);
CREATE INDEX nutrient_profile_snapshot_time_idx ON public.nutrient_profile_snapshot (created_at);

COMMENT ON TABLE public.nutrient_profile_snapshot IS 'OKR 2: how well a user''s pantry covers their daily nutrient targets, saved each time the pantry or targets change';
COMMENT ON COLUMN public.nutrient_profile_snapshot.nutrients IS '{"protein": {"per_day": 41.3, "target": 68, "pct": 60.7, "met": false}, ...} for each nutrient with a target';
COMMENT ON COLUMN public.nutrient_profile_snapshot.achievement_pct IS 'nutrients_met / nutrients_total x 100';
COMMENT ON COLUMN public.nutrient_profile_snapshot.avg_coverage_pct IS 'Average of each nutrient''s % of target, capped at 100 per nutrient';
COMMENT ON COLUMN public.nutrient_profile_snapshot.goal_met IS 'True when every nutrient is at 100% or more of its daily target';
COMMENT ON COLUMN public.nutrient_profile_snapshot.recommended_food_ids IS 'Pantry foods this user had added from a recommendation (recommendation_event added rows). Set by trigger';
COMMENT ON COLUMN public.nutrient_profile_snapshot.pantry_signature IS 'Pantry foods, quantities, plan days and targets. The app skips saving when it matches the last snapshot';

-- Fill recommended_food_ids from recommendation_event. Runs as the inserting user, who can read
-- their own events (RLS from 0003), so it only ever sees that user's rows.
CREATE OR REPLACE FUNCTION public.nutrient_snapshot_fill_recommended()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.recommended_food_ids := coalesce((
    SELECT array_agg(DISTINCT f ORDER BY f)
    FROM unnest(NEW.pantry_food_ids) AS f
    WHERE EXISTS (
      SELECT 1 FROM public.recommendation_event r
      WHERE r.user_id = NEW.user_id AND r.event_type = 'added' AND r.food_id = f)
  ), '{}');
  RETURN NEW;
END;
$$;

CREATE TRIGGER nutrient_snapshot_fill_recommended
  BEFORE INSERT ON public.nutrient_profile_snapshot
  FOR EACH ROW EXECUTE FUNCTION public.nutrient_snapshot_fill_recommended();

-- Snapshots are append-only history for users: write and read their own rows, never change or delete.
GRANT SELECT, INSERT ON public.nutrient_profile_snapshot TO authenticated;
GRANT ALL ON public.nutrient_profile_snapshot TO service_role;

ALTER TABLE public.nutrient_profile_snapshot ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users save own nutrient snapshots" ON public.nutrient_profile_snapshot FOR INSERT TO authenticated
  WITH CHECK (
    user_id = auth.uid()
    AND EXISTS (SELECT 1 FROM public.pantry p WHERE p.pantry_id = nutrient_profile_snapshot.pantry_id AND p.user_id = auth.uid())
  );
CREATE POLICY "Users read own nutrient snapshots" ON public.nutrient_profile_snapshot FOR SELECT TO authenticated
  USING (user_id = auth.uid());

-- 2. Each user's latest snapshot as of the end of a day (UTC). The pantry is current state, so a user
--    counts with whatever their pantry looked like last, even if it hasn't changed in a while.
CREATE OR REPLACE FUNCTION analytics.nutrient_goal_latest(
  p_as_of date DEFAULT (now() AT TIME ZONE 'UTC')::date)
RETURNS SETOF public.nutrient_profile_snapshot
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT DISTINCT ON (s.user_id) s.*
  FROM public.nutrient_profile_snapshot s
  WHERE (s.created_at AT TIME ZONE 'UTC')::date <= p_as_of
  ORDER BY s.user_id, s.created_at DESC, s.nutrient_profile_snapshot_id DESC;
$$;

-- 3. The OKR 2 numbers.
--    goal_met_pct          = % of tracked users whose pantry meets every nutrient target (headline)
--    avg_achievement_pct   = average share of nutrients met per user
--    *_with_recs / *_without_recs = the same, split by whether the pantry holds a food the user
--                            added from a recommendation (OKR 1 -> OKR 2 link)
--    reached_in_window     = users with at least one goal_met snapshot in the last p_window_days
CREATE OR REPLACE FUNCTION analytics.nutrient_goal_rate(
  p_as_of date DEFAULT (now() AT TIME ZONE 'UTC')::date,
  p_window_days int DEFAULT 30)
RETURNS TABLE (as_of date, window_days int, tracked_users int, goal_met_users int, goal_met_pct numeric,
               avg_achievement_pct numeric, avg_coverage_pct numeric,
               users_with_recs int, goal_met_pct_with_recs numeric, goal_met_pct_without_recs numeric,
               avg_achievement_with_recs numeric, avg_achievement_without_recs numeric,
               reached_in_window int, snapshots_in_window int)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  WITH l AS (
    SELECT l.*, cardinality(l.recommended_food_ids) > 0 AS has_recs
    FROM analytics.nutrient_goal_latest(p_as_of) l
  ), w AS (
    SELECT s.user_id, s.goal_met
    FROM public.nutrient_profile_snapshot s
    WHERE (s.created_at AT TIME ZONE 'UTC')::date > p_as_of - p_window_days
      AND (s.created_at AT TIME ZONE 'UTC')::date <= p_as_of
  )
  SELECT p_as_of, p_window_days,
         (SELECT count(*) FROM l)::int,
         (SELECT count(*) FILTER (WHERE goal_met) FROM l)::int,
         (SELECT round(100.0 * count(*) FILTER (WHERE goal_met) / NULLIF(count(*), 0), 1) FROM l),
         (SELECT round(avg(achievement_pct), 1) FROM l),
         (SELECT round(avg(avg_coverage_pct), 1) FROM l),
         (SELECT count(*) FILTER (WHERE has_recs) FROM l)::int,
         (SELECT round(100.0 * count(*) FILTER (WHERE goal_met) / NULLIF(count(*), 0), 1) FROM l WHERE has_recs),
         (SELECT round(100.0 * count(*) FILTER (WHERE goal_met) / NULLIF(count(*), 0), 1) FROM l WHERE NOT has_recs),
         (SELECT round(avg(achievement_pct), 1) FROM l WHERE has_recs),
         (SELECT round(avg(achievement_pct), 1) FROM l WHERE NOT has_recs),
         (SELECT count(DISTINCT user_id) FILTER (WHERE goal_met) FROM w)::int,
         (SELECT count(*) FROM w)::int;
$$;

-- 4. Which nutrients pantries miss most, from each user's latest snapshot.
CREATE OR REPLACE FUNCTION analytics.nutrient_goal_by_nutrient(
  p_as_of date DEFAULT (now() AT TIME ZONE 'UTC')::date)
RETURNS TABLE (nutrient text, users int, met_users int, met_pct numeric, avg_pct numeric)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT n.key, count(*)::int,
         count(*) FILTER (WHERE (n.value->>'met')::boolean)::int,
         round(100.0 * count(*) FILTER (WHERE (n.value->>'met')::boolean) / NULLIF(count(*), 0), 1),
         round(avg(least((n.value->>'pct')::numeric, 100)), 1)
  FROM analytics.nutrient_goal_latest(p_as_of) l
  CROSS JOIN LATERAL jsonb_each(l.nutrients) n
  GROUP BY n.key;
$$;

-- 5. Daily history, like churn_snapshot (0004) and login_frequency_snapshot (0005).
CREATE TABLE IF NOT EXISTS analytics.nutrient_goal_daily (
  as_of date NOT NULL,
  window_days int NOT NULL,
  tracked_users int NOT NULL,
  goal_met_users int NOT NULL,
  goal_met_pct numeric,
  avg_achievement_pct numeric,
  avg_coverage_pct numeric,
  users_with_recs int NOT NULL,
  goal_met_pct_with_recs numeric,
  goal_met_pct_without_recs numeric,
  reached_in_window int NOT NULL,
  snapshots_in_window int NOT NULL,
  computed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (as_of, window_days)
);
ALTER TABLE analytics.nutrient_goal_daily ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION analytics.record_nutrient_goal_snapshot(
  p_as_of date DEFAULT (now() AT TIME ZONE 'UTC')::date,
  p_window_days int DEFAULT 30)
RETURNS void
LANGUAGE sql
SET search_path = ''
AS $$
  INSERT INTO analytics.nutrient_goal_daily
    (as_of, window_days, tracked_users, goal_met_users, goal_met_pct, avg_achievement_pct, avg_coverage_pct,
     users_with_recs, goal_met_pct_with_recs, goal_met_pct_without_recs, reached_in_window, snapshots_in_window)
  SELECT r.as_of, r.window_days, r.tracked_users, r.goal_met_users, r.goal_met_pct, r.avg_achievement_pct,
         r.avg_coverage_pct, r.users_with_recs, r.goal_met_pct_with_recs, r.goal_met_pct_without_recs,
         r.reached_in_window, r.snapshots_in_window
  FROM analytics.nutrient_goal_rate(p_as_of, p_window_days) r
  ON CONFLICT (as_of, window_days) DO UPDATE SET
    tracked_users = EXCLUDED.tracked_users, goal_met_users = EXCLUDED.goal_met_users,
    goal_met_pct = EXCLUDED.goal_met_pct, avg_achievement_pct = EXCLUDED.avg_achievement_pct,
    avg_coverage_pct = EXCLUDED.avg_coverage_pct, users_with_recs = EXCLUDED.users_with_recs,
    goal_met_pct_with_recs = EXCLUDED.goal_met_pct_with_recs,
    goal_met_pct_without_recs = EXCLUDED.goal_met_pct_without_recs,
    reached_in_window = EXCLUDED.reached_in_window, snapshots_in_window = EXCLUDED.snapshots_in_window,
    computed_at = now();
$$;

REVOKE ALL ON ALL TABLES IN SCHEMA analytics FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA analytics FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.nutrient_snapshot_fill_recommended() FROM PUBLIC, anon, authenticated;

SELECT analytics.record_nutrient_goal_snapshot();

-- Run it every day at 00:25 UTC, after the churn (00:15) and login frequency (00:20) snapshots.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
    PERFORM cron.schedule('kiwi-nutrient-goal-snapshot', '25 0 * * *', 'SELECT analytics.record_nutrient_goal_snapshot()');
  ELSE
    RAISE NOTICE 'pg_cron is not enabled; run SELECT analytics.record_nutrient_goal_snapshot() yourself or schedule it elsewhere';
  END IF;
END;
$$;

