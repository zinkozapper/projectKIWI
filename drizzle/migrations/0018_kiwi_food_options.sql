-- Purchase options ("prep styles") for a food: chicken breast -> raw, rotisserie, frozen, canned.
-- The AI food workflow suggests them when a food is added (and scripts/kroger/options-backfill.mjs for the
-- existing catalog); each option is priced at Kroger like the food itself. Nutrients stay the food's own.
--
--   food_option         One row per food per form (fresh, frozen, canned, dried, ready_to_eat), so options stay
--                       general: never two frozen or two canned kinds. price = per serving at the default store
--                       (84601), 0 = unknown.
--   food_option_price   Price of an option at a store (same columns as food_price).
--   shopping_list_item.food_option_id
--                       The option a shopper picked for a list item. NULL = no preference: the item is priced at
--                       the average of the food's priced options (food.price holds that average).
-- Rules: docs/kroger-price-selection-rules.md "Purchase options". Safe to run more than once.

CREATE TABLE IF NOT EXISTS public.food_option (
  food_option_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  food_id integer NOT NULL REFERENCES public.food(food_id) ON DELETE CASCADE,
  form text NOT NULL CHECK (form IN ('fresh', 'frozen', 'canned', 'dried', 'ready_to_eat')),
  label text NOT NULL CHECK (char_length(label) BETWEEN 1 AND 30),
  search_term text NOT NULL,
  must text[] NOT NULL DEFAULT '{}',
  basis text NOT NULL DEFAULT 'as_bought' CHECK (basis IN ('as_bought', 'prepared')),
  package_yield numeric NOT NULL DEFAULT 1 CHECK (package_yield > 0 AND package_yield <= 1),
  unit_grams numeric CHECK (unit_grams > 0),
  price numeric(10,2) NOT NULL DEFAULT 0 CHECK (price >= 0),
  sort_order smallint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (food_id, form)
);
CREATE INDEX IF NOT EXISTS food_option_food_idx ON public.food_option (food_id);
COMMENT ON TABLE public.food_option IS 'How a food is sold (raw, rotisserie, frozen, canned …), one per form, each with its own price';
COMMENT ON COLUMN public.food_option.basis IS 'as_bought = priced on the food''s raw/dry serving grams; prepared = priced on its cooked/ready serving grams (factor × 100)';
COMMENT ON COLUMN public.food_option.package_yield IS 'Usable share of the package (a drained can ≈ 0.6)';
COMMENT ON COLUMN public.food_option.unit_grams IS 'Edible grams in one item when it is sold per item with no weight (a rotisserie chicken ≈ 700 g)';

CREATE TABLE IF NOT EXISTS public.food_option_price (
  food_option_id bigint NOT NULL REFERENCES public.food_option(food_option_id) ON DELETE CASCADE,
  location_id text NOT NULL REFERENCES public.kroger_store(location_id) ON DELETE CASCADE,
  source_location_id text REFERENCES public.kroger_store(location_id) ON DELETE SET NULL,
  product_id text NOT NULL,
  upc text,
  brand text,
  description text,
  package_size text,
  sold_by text,
  package_price numeric(10,2) NOT NULL CHECK (package_price > 0),
  package_grams numeric,
  serving_grams numeric NOT NULL CHECK (serving_grams > 0),
  price_per_serving numeric(10,4) NOT NULL CHECK (price_per_serving >= 0),
  store_brand boolean NOT NULL DEFAULT true,
  flags text,
  fetched_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (food_option_id, location_id)
);
CREATE INDEX IF NOT EXISTS food_option_price_location_idx ON public.food_option_price (location_id);

ALTER TABLE public.shopping_list_item
  ADD COLUMN IF NOT EXISTS food_option_id bigint REFERENCES public.food_option(food_option_id) ON DELETE SET NULL;
COMMENT ON COLUMN public.shopping_list_item.food_option_id IS 'Purchase option the shopper picked; NULL = average of the food''s options';

-- Everyone can read options and prices; only the service role writes them.
ALTER TABLE public.food_option ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.food_option_price ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS food_option_read ON public.food_option;
CREATE POLICY food_option_read ON public.food_option FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS food_option_price_read ON public.food_option_price;
CREATE POLICY food_option_price_read ON public.food_option_price FOR SELECT TO anon, authenticated USING (true);
REVOKE INSERT, UPDATE, DELETE ON public.food_option, public.food_option_price FROM anon, authenticated;
GRANT SELECT ON public.food_option, public.food_option_price TO anon, authenticated;
GRANT ALL ON public.food_option, public.food_option_price TO service_role;

-- Self-hosted price refresh (migration 0013): new options count as a catalog change, so the next store
-- refresh prices them. Skipped where 0013 isn't applied (the hosted app uses the default-store prices).
DO $$
BEGIN
  IF to_regprocedure('public.price_catalog_food_added()') IS NOT NULL THEN
    DROP TRIGGER IF EXISTS price_catalog_option_added ON public.food_option;
    CREATE TRIGGER price_catalog_option_added AFTER INSERT ON public.food_option
    FOR EACH STATEMENT EXECUTE FUNCTION public.price_catalog_food_added();
  END IF;
END $$;
