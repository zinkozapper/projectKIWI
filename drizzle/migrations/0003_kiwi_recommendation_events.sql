-- OKR 1 (effective shopping recommendations): log what the app recommends and what users do with it.
-- One row per event. A "shown" row is one impression of one recommended food; an "added" or
-- "dismissed" row carries the same impression_id, so conversions link back to the exact impression.
CREATE TABLE public.recommendation_event (
  recommendation_event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES public.users(user_id) ON DELETE CASCADE,
  impression_id uuid NOT NULL,
  event_type varchar NOT NULL CHECK (event_type IN ('shown', 'added', 'dismissed')),
  source varchar NOT NULL CHECK (source IN ('nutrient_gap', 'pairing')),
  food_id integer NOT NULL REFERENCES public.food(food_id),
  anchor_food_id integer REFERENCES public.food(food_id),
  rank smallint,
  shopping_list_id integer REFERENCES public.shopping_list(shopping_list_id) ON DELETE SET NULL,
  shopping_list_item_id integer REFERENCES public.shopping_list_item(shopping_list_item_id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  -- Each impression is shown once and added/dismissed at most once, so double clicks don't double count.
  CONSTRAINT recommendation_event_once UNIQUE (impression_id, event_type)
);

CREATE INDEX recommendation_event_user_time_idx ON public.recommendation_event (user_id, created_at);
CREATE INDEX recommendation_event_type_time_idx ON public.recommendation_event (event_type, created_at);

COMMENT ON TABLE public.recommendation_event IS 'Recommendation impressions (shown) and outcomes (added, dismissed) for the add-to-list rate metric';
COMMENT ON COLUMN public.recommendation_event.source IS 'nutrient_gap = Suggestions card on /plan, pairing = "Pairs well with" card';
COMMENT ON COLUMN public.recommendation_event.anchor_food_id IS 'For pairing recommendations, the list food the pairing was for';
COMMENT ON COLUMN public.recommendation_event.rank IS 'Position in the card, starting at 1';

-- Events are append-only for users: they can write and read their own rows, never change or delete them.
GRANT SELECT, INSERT ON public.recommendation_event TO authenticated;
GRANT ALL ON public.recommendation_event TO service_role;

ALTER TABLE public.recommendation_event ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users log own recommendation events" ON public.recommendation_event FOR INSERT TO authenticated
  WITH CHECK (
    user_id = auth.uid()
    AND (shopping_list_id IS NULL OR EXISTS (
      SELECT 1 FROM public.shopping_list s WHERE s.shopping_list_id = recommendation_event.shopping_list_id AND s.user_id = auth.uid()))
  );
CREATE POLICY "Users read own recommendation events" ON public.recommendation_event FOR SELECT TO authenticated
  USING (user_id = auth.uid());
