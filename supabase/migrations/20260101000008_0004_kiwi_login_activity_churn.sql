-- OKR 4 (retention): track login activity, mark inactive users, and compute churn % automatically.
--
-- Definitions (the window is 30 days by default; every function takes it as a parameter):
--   active day   = a day a user signed up, signed in, or opened the app with a saved session.
--   inactive     = no active day in the last 30 days (last active day is 30+ days ago).
--   churn %      = of the users who were active in the previous 30-day window,
--                  the share with no activity at all in the current 30-day window.
-- Sign-ins alone undercount: Supabase refreshes saved sessions without a new sign-in, so a loyal
-- user with "Remember me" may never sign in again. That's why the app also logs 'app_open'.

-- 1. The login table. The sign-in page already inserts into it, so create it only if missing and
--    add any columns an older hand-made version lacks.
CREATE TABLE IF NOT EXISTS public.user_login_events (
  login_event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  event_type varchar NOT NULL DEFAULT 'sign_in',
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.user_login_events ADD COLUMN IF NOT EXISTS event_type varchar NOT NULL DEFAULT 'sign_in';
ALTER TABLE public.user_login_events ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE public.user_login_events ALTER COLUMN user_id SET DEFAULT auth.uid();
ALTER TABLE public.user_login_events DROP CONSTRAINT IF EXISTS user_login_events_event_type_check;
ALTER TABLE public.user_login_events ADD CONSTRAINT user_login_events_event_type_check
  CHECK (event_type IN ('sign_up', 'sign_in', 'app_open'));

CREATE INDEX IF NOT EXISTS user_login_events_user_time_idx ON public.user_login_events (user_id, created_at);
CREATE INDEX IF NOT EXISTS user_login_events_time_idx ON public.user_login_events (created_at);

COMMENT ON TABLE public.user_login_events IS 'Login activity for retention/churn (OKR 4). sign_up and sign_in come from a trigger on auth.users; app_open comes from the app';

-- Users may only add their own app_open rows and read their own rows. sign_up/sign_in rows come from
-- the trigger below, which works for every sign-in method (password, Google, passkey).
GRANT SELECT, INSERT ON public.user_login_events TO authenticated;
GRANT ALL ON public.user_login_events TO service_role;
-- An older hand-made table may use a serial id; inserts then need its sequence too.
DO $$
DECLARE seq text;
BEGIN
  FOR seq IN SELECT pg_get_serial_sequence('public.user_login_events', attname) FROM pg_attribute
             WHERE attrelid = 'public.user_login_events'::regclass AND attnum > 0 AND NOT attisdropped LOOP
    IF seq IS NOT NULL THEN EXECUTE format('GRANT USAGE ON SEQUENCE %s TO authenticated', seq); END IF;
  END LOOP;
END;
$$;
ALTER TABLE public.user_login_events ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Users log own app opens" ON public.user_login_events;
CREATE POLICY "Users log own app opens" ON public.user_login_events FOR INSERT TO authenticated
  WITH CHECK (user_id = auth.uid() AND event_type = 'app_open');
DROP POLICY IF EXISTS "Users read own login events" ON public.user_login_events;
CREATE POLICY "Users read own login events" ON public.user_login_events FOR SELECT TO authenticated
  USING (user_id = auth.uid());

-- 2. Log sign-ups and sign-ins from auth.users. Supabase updates last_sign_in_at on every real
--    sign-in (not on token refresh). The EXCEPTION block means logging can never block a login.
CREATE OR REPLACE FUNCTION public.log_kiwi_auth_event()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  BEGIN
    IF TG_OP = 'INSERT' THEN
      INSERT INTO public.user_login_events (user_id, event_type, created_at)
      VALUES (NEW.id, 'sign_up', coalesce(NEW.created_at, now()));
    ELSIF NEW.last_sign_in_at IS NOT NULL THEN
      INSERT INTO public.user_login_events (user_id, event_type, created_at)
      VALUES (NEW.id, 'sign_in', NEW.last_sign_in_at);
    END IF;
  EXCEPTION WHEN others THEN
    RAISE WARNING 'log_kiwi_auth_event failed: %', SQLERRM;
  END;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.log_kiwi_auth_event() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS on_kiwi_auth_user_created ON auth.users;
CREATE TRIGGER on_kiwi_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.log_kiwi_auth_event();

DROP TRIGGER IF EXISTS on_kiwi_auth_user_signed_in ON auth.users;
CREATE TRIGGER on_kiwi_auth_user_signed_in
  AFTER UPDATE OF last_sign_in_at ON auth.users
  FOR EACH ROW
  WHEN (NEW.last_sign_in_at IS DISTINCT FROM OLD.last_sign_in_at)
  EXECUTE FUNCTION public.log_kiwi_auth_event();

-- 3. Backfill history for users who existed before this migration, so churn isn't empty on day one.
INSERT INTO public.user_login_events (user_id, event_type, created_at)
SELECT u.id, 'sign_up', u.created_at FROM auth.users u
WHERE NOT EXISTS (SELECT 1 FROM public.user_login_events e WHERE e.user_id = u.id AND e.event_type = 'sign_up');
INSERT INTO public.user_login_events (user_id, event_type, created_at)
SELECT u.id, 'sign_in', u.last_sign_in_at FROM auth.users u
WHERE u.last_sign_in_at IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM public.user_login_events e
                  WHERE e.user_id = u.id AND e.event_type = 'sign_in' AND e.created_at = u.last_sign_in_at);

-- 4. Analytics lives in its own schema. The Supabase API only serves the public schema, so nothing
--    below is reachable from the app; it's for the SQL editor and the scheduled job.
CREATE SCHEMA IF NOT EXISTS analytics;
REVOKE ALL ON SCHEMA analytics FROM PUBLIC, anon, authenticated;

-- One row per user per active day (UTC). Repeat logins on the same day count once.
CREATE OR REPLACE VIEW analytics.user_active_day AS
SELECT DISTINCT user_id, (created_at AT TIME ZONE 'UTC')::date AS active_date
FROM public.user_login_events;

-- Every user with their last active day and an active/inactive mark.
CREATE OR REPLACE FUNCTION analytics.user_status(p_window_days int DEFAULT 30, p_as_of date DEFAULT (now() AT TIME ZONE 'UTC')::date)
RETURNS TABLE (user_id uuid, email text, signed_up_at timestamptz, last_active_date date, days_inactive int, status text)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT u.id, u.email::text, u.created_at, a.last_active,
         (p_as_of - a.last_active)::int,
         CASE WHEN a.last_active IS NULL OR a.last_active <= p_as_of - p_window_days THEN 'inactive' ELSE 'active' END
  FROM auth.users u
  LEFT JOIN LATERAL (
    SELECT max(d.active_date) AS last_active FROM analytics.user_active_day d
    WHERE d.user_id = u.id AND d.active_date <= p_as_of
  ) a ON true
  WHERE (u.created_at AT TIME ZONE 'UTC')::date <= p_as_of;
$$;

-- Today's view with the default 30-day window, for quick lookups: SELECT * FROM analytics.user_status_now;
CREATE OR REPLACE VIEW analytics.user_status_now AS SELECT * FROM analytics.user_status();

-- Churn for the window ending on p_as_of.
--   current window  = (as_of - window, as_of]            e.g. the last 30 days, today included
--   previous window = (as_of - 2*window, as_of - window]  the 30 days before that
--   base            = users active in the previous window
--   churned         = base users with no active day in the current window
CREATE OR REPLACE FUNCTION analytics.churn_rate(p_as_of date DEFAULT (now() AT TIME ZONE 'UTC')::date, p_window_days int DEFAULT 30)
RETURNS TABLE (as_of date, window_days int, base_users int, retained_users int, churned_users int, churn_pct numeric, new_users int)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  WITH prev AS (
    SELECT DISTINCT d.user_id FROM analytics.user_active_day d
    WHERE d.active_date > p_as_of - 2 * p_window_days AND d.active_date <= p_as_of - p_window_days
  ), cur AS (
    SELECT DISTINCT d.user_id FROM analytics.user_active_day d
    WHERE d.active_date > p_as_of - p_window_days AND d.active_date <= p_as_of
  )
  SELECT p_as_of, p_window_days,
         (SELECT count(*) FROM prev)::int,
         (SELECT count(*) FROM prev JOIN cur USING (user_id))::int,
         (SELECT count(*) FROM prev WHERE user_id NOT IN (SELECT user_id FROM cur))::int,
         round(100.0 * (SELECT count(*) FROM prev WHERE user_id NOT IN (SELECT user_id FROM cur))
               / NULLIF((SELECT count(*) FROM prev), 0), 1),
         (SELECT count(*) FROM auth.users u
          WHERE (u.created_at AT TIME ZONE 'UTC')::date > p_as_of - p_window_days
            AND (u.created_at AT TIME ZONE 'UTC')::date <= p_as_of)::int;
$$;

-- 5. A daily snapshot table, so the churn % history is kept even if the definition changes later.
CREATE TABLE IF NOT EXISTS analytics.churn_snapshot (
  as_of date NOT NULL,
  window_days int NOT NULL,
  base_users int NOT NULL,
  retained_users int NOT NULL,
  churned_users int NOT NULL,
  churn_pct numeric,
  new_users int NOT NULL,
  total_users int NOT NULL,
  inactive_users int NOT NULL,
  computed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (as_of, window_days)
);

CREATE OR REPLACE FUNCTION analytics.record_churn_snapshot(p_as_of date DEFAULT (now() AT TIME ZONE 'UTC')::date, p_window_days int DEFAULT 30)
RETURNS void
LANGUAGE sql
SET search_path = ''
AS $$
  INSERT INTO analytics.churn_snapshot
    (as_of, window_days, base_users, retained_users, churned_users, churn_pct, new_users, total_users, inactive_users)
  SELECT c.as_of, c.window_days, c.base_users, c.retained_users, c.churned_users, c.churn_pct, c.new_users,
         (SELECT count(*) FROM analytics.user_status(p_window_days, p_as_of))::int,
         (SELECT count(*) FROM analytics.user_status(p_window_days, p_as_of) s WHERE s.status = 'inactive')::int
  FROM analytics.churn_rate(p_as_of, p_window_days) c
  ON CONFLICT (as_of, window_days) DO UPDATE SET
    base_users = EXCLUDED.base_users, retained_users = EXCLUDED.retained_users,
    churned_users = EXCLUDED.churned_users, churn_pct = EXCLUDED.churn_pct, new_users = EXCLUDED.new_users,
    total_users = EXCLUDED.total_users, inactive_users = EXCLUDED.inactive_users, computed_at = now();
$$;

REVOKE ALL ON ALL TABLES IN SCHEMA analytics FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA analytics FROM PUBLIC, anon, authenticated;

SELECT analytics.record_churn_snapshot();

-- 6. Run the snapshot every day at 00:15 UTC with pg_cron. Skipped quietly where pg_cron isn't available.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_available_extensions WHERE name = 'pg_cron') THEN
    BEGIN
      CREATE EXTENSION IF NOT EXISTS pg_cron;
      PERFORM cron.schedule('kiwi-churn-snapshot', '15 0 * * *', 'SELECT analytics.record_churn_snapshot()');
    EXCEPTION WHEN others THEN
      RAISE NOTICE 'Could not schedule with pg_cron (%). Enable it under Database > Extensions and rerun this block', SQLERRM;
    END;
  ELSE
    RAISE NOTICE 'pg_cron is not available; run SELECT analytics.record_churn_snapshot() yourself or schedule it elsewhere';
  END IF;
END;
$$;
