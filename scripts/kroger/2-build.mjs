// Step 2: turn the reviewed candidates into prices and SQL.
//   node scripts/kroger/2-build.mjs [--zip 84601]
//   Input : data/kroger/<zip>/store.json, candidates.csv (exactly one "x" per food you want priced)
//   Output: data/kroger/<zip>/food-prices.csv  — one row per food, with flags to check
//           data/kroger/<zip>/food-prices.sql  — upserts kroger_store, zip_store, food_price;
//                                                for the default ZIP also sets food.price (the app's fallback price)
// The SQL needs the service role / SQL editor (RLS blocks writes from the app's key).
import fs from 'node:fs';
import path from 'node:path';
import { OUT, ROOT, RULES, isStoreBrand, readCsv, toCsv } from './lib.mjs';

const arg = (k, d) => { const i = process.argv.indexOf(k); return i > -1 ? process.argv[i + 1] : d; };
const zip = arg('--zip', RULES.defaultZip);
const dir = path.join(OUT, zip);
const { store } = JSON.parse(fs.readFileSync(path.join(dir, 'store.json'), 'utf8'));
const rows = readCsv(path.join(dir, 'candidates.csv'));

const byFood = new Map();
for (const r of rows) { if (!byFood.has(r.food_id)) byFood.set(r.food_id, { name: r.food, picks: [] }); if (r.selected.trim().toLowerCase() === 'x') byFood.get(r.food_id).picks.push(r); }

const q = v => v == null || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`;
const n = v => v == null || v === '' || !Number.isFinite(+v) ? 'NULL' : String(+v);
const out = [['food_id', 'food', 'brand', 'description', 'size', 'regular', 'serving_g', 'price_per_serving', 'how', 'flags']];
const values = [], problems = [];
for (const [id, { name, picks }] of byFood) {
  if (picks.length !== 1) { problems.push(`${name}: ${picks.length ? picks.length + ' rows marked x' : 'nothing selected'}`); continue; }
  const p = picks[0];
  if (!p.price_per_serving) { problems.push(`${name}: selected row has no price per serving (${p.reason || 'see how/flags'})`); continue; }
  out.push([id, name, p.brand, p.description, p.size, p.regular, p.serving_g, (+p.price_per_serving).toFixed(4), p.how, p.flags]);
  values.push(`(${id}, ${q(store.location_id)}, ${q(p.product_id)}, ${q(p.upc)}, ${q(p.brand)}, ${q(p.description)}, ${q(p.size)}, ${q(p.sold_by)}, ${n(p.regular)}, ${n(p.package_g)}, ${n(p.serving_g || 1)}, ${(+p.price_per_serving).toFixed(4)}, ${isStoreBrand(p)}, ${q(p.flags)})`);
}
fs.writeFileSync(path.join(dir, 'food-prices.csv'), toCsv(out));

const sql = [`-- Generated by scripts/kroger/2-build.mjs for ZIP ${zip} on ${new Date().toISOString()}`, 'BEGIN;',
  `INSERT INTO public.kroger_store (location_id, chain, name, address, city, state, zip_code, latitude, longitude, fetched_at)
VALUES (${q(store.location_id)}, ${q(store.chain)}, ${q(store.name)}, ${q(store.address)}, ${q(store.city)}, ${q(store.state)}, ${q(store.zip_code)}, ${n(store.latitude)}, ${n(store.longitude)}, now())
ON CONFLICT (location_id) DO UPDATE SET chain = EXCLUDED.chain, name = EXCLUDED.name, address = EXCLUDED.address, city = EXCLUDED.city, state = EXCLUDED.state, zip_code = EXCLUDED.zip_code, latitude = EXCLUDED.latitude, longitude = EXCLUDED.longitude, fetched_at = now();`,
  `INSERT INTO public.zip_store (zip_code, location_id, fetched_at) VALUES (${q(zip)}, ${q(store.location_id)}, now())
ON CONFLICT (zip_code) DO UPDATE SET location_id = EXCLUDED.location_id, fetched_at = now();`];
if (values.length) sql.push(`INSERT INTO public.food_price (food_id, location_id, product_id, upc, brand, description, package_size, sold_by, package_price, package_grams, serving_grams, price_per_serving, store_brand, flags)
VALUES
${values.join(',\n')}
ON CONFLICT (food_id, location_id) DO UPDATE SET product_id = EXCLUDED.product_id, upc = EXCLUDED.upc, brand = EXCLUDED.brand, description = EXCLUDED.description,
  package_size = EXCLUDED.package_size, sold_by = EXCLUDED.sold_by, package_price = EXCLUDED.package_price, package_grams = EXCLUDED.package_grams,
  serving_grams = EXCLUDED.serving_grams, price_per_serving = EXCLUDED.price_per_serving, store_brand = EXCLUDED.store_brand, flags = EXCLUDED.flags, fetched_at = now();`);
if (zip === RULES.defaultZip && values.length) sql.push(`-- Default ZIP: food.price is the fallback price per serving the app shows everyone
UPDATE public.food f SET price = round(fp.price_per_serving, 2) FROM public.food_price fp WHERE fp.food_id = f.food_id AND fp.location_id = ${q(store.location_id)};`);
sql.push('COMMIT;');
fs.writeFileSync(path.join(dir, 'food-prices.sql'), sql.join('\n\n') + '\n');

console.log(`${values.length} foods priced at ${store.name}. Wrote ${path.relative(ROOT, dir)}/food-prices.csv and food-prices.sql`);
const flagged = out.slice(1).filter(r => r[9]);
if (flagged.length) { console.log(`\nCheck these (${flagged.length}):`); flagged.forEach(r => console.log(`  ${r[1]}: ${r[9]}`)); }
if (problems.length) { console.log(`\nNot priced (${problems.length}):`); problems.forEach(p => console.log('  ' + p)); }
